"""SYNTHETIC test case for calibration.

Everything in this module is synthetic: forcing, the "true" parameters and the
observations are generated by a seeded random number generator. They are not
field data and say nothing about any real site. They exist so DREAM and PEST++
can be checked on a case whose parameters are known.

Treatment train (units in series):

1. Woodchip denitrifying bioreactor: 4 tanks in series, Michaelis-Menten NO3-N
   removal, Arrhenius temperature dependence.
2. Eggshell P-sorption reactor: 3 tanks in series, kinetic Langmuir sorption
   with a finite capacity that depletes.

Inflow above the design flow bypasses each unit. Observations are the
flow-weighted NO3-N and PO4-P concentrations at the train outlet (after the
bypass junction), every 3rd day, with heteroscedastic Gaussian noise.
"""
from __future__ import annotations

import numpy as np

from aquasimu import AdvDiffReactor, Forcing, simulate_train, train_balance

# name, true value, lower, upper, log10 transform?
PARAMS = [
    ("vmax_N", 7.0, 0.5, 40.0, True),     # g N / m3 pore water / d at 20 degC
    ("K_N", 3.0, 0.1, 30.0, True),         # g N / m3
    ("theta_N", 1.08, 1.00, 1.25, False),  # Arrhenius factor
    ("k_ads", 0.006, 1e-4, 0.05, True),    # m3 / g / d
    ("q_max", 0.9, 0.05, 6.0, True),       # g P / kg eggshell
]
NAMES = [p[0] for p in PARAMS]
TRUE = np.array([p[1] for p in PARAMS])
LO = np.array([p[2] for p in PARAMS])
HI = np.array([p[3] for p in PARAMS])
LOG = np.array([p[4] for p in PARAMS])

# Fixed design of the synthetic site. Not calibrated.
WOOD = dict(
    name="woodchip", n_cells=4, volume=30.0, q_design=50.0, scheme="upwind",
    n_kinetics="mm", cN0=9.0, cP0=0.5,
)
EGG = dict(
    name="eggshell", n_cells=3, volume=1.5, q_design=50.0, scheme="upwind",
    p_kinetics="langmuir", rho_bulk_over_theta=1100.0 / 0.45, k_des=0.001, theta_p=1.0,
    cN0=9.0, cP0=0.5,
)

NOISE_N = (0.15, 0.05)       # sigma = a + b * y   (g/m3)
NOISE_P = (0.01, 0.05)

OBS_DAYS = np.arange(2, 365, 3)


def to_internal(x):
    """Physical parameters to the sampling space (log10 for scale parameters)."""
    x = np.asarray(x, float)
    return np.where(LOG, np.log10(x), x)


def to_physical(z):
    z = np.asarray(z, float)
    return np.where(LOG, 10.0 ** z, z)


Z_LO, Z_HI, Z_TRUE = to_internal(LO), to_internal(HI), to_internal(TRUE)


def make_forcing(seed: int = 2026, days: int = 365) -> Forcing:
    """Synthetic daily forcing for one year, including storms above the design flow."""
    rng = np.random.default_rng(seed)
    day = np.arange(days)
    season = np.sin(2 * np.pi * (day - 100) / 365)
    flow = 18.0 * (1 + 0.5 * np.exp(-((day - 105) / 30.0) ** 2)) * rng.lognormal(0, 0.25, days)
    for _ in range(14):
        start = rng.integers(0, days - 3)
        duration = rng.integers(1, 4)
        flow[start:start + duration] += rng.uniform(40, 110)
    temperature = np.clip(10.5 + 10.5 * season + rng.normal(0, 1.2, days), 0.5, None)
    cin_n = np.clip(9.0 + 3.0 * np.cos(2 * np.pi * (day - 60) / 365) + rng.normal(0, 1.0, days), 2, None)
    cin_p = np.clip(0.55 + 0.25 * np.tanh((flow - 30) / 30) + rng.normal(0, 0.08, days), 0.08, None)
    return Forcing(flow, temperature, cin_n, cin_p, dt=1.0, start="2025-01-01")


def build_train(x):
    """Physical parameter vector, in PARAMS order, as two advective-diffusive units."""
    vmax, half_sat, theta_n, k_ads, q_max = [float(v) for v in x]
    wood = AdvDiffReactor(vmax_n=vmax, K_n=half_sat, theta_n=theta_n, **WOOD)
    egg = AdvDiffReactor(k_ads=k_ads, q_max=q_max, **EGG)
    return [wood, egg]


def run_model(x, forcing: Forcing, tol: float = 1e-6, nsub=None):
    """Run the train. Mass balance is checked inside (both units and the train)."""
    results = simulate_train(build_train(x), forcing, nsub=nsub, tol=tol)
    balance = train_balance(results, tol)
    return dict(
        cN=results[-1].cout_N,
        cP=results[-1].cout_P,
        kgN=results[0].balance()["kgN_retained_per_yr"],
        kgP=results[1].balance()["kgP_retained_per_yr"],
        results=results,
        train_balance=balance,
    )


def make_observations(forcing: Forcing, seed: int = 7):
    """Synthetic observations: truth from TRUE parameters plus heteroscedastic noise."""
    out = run_model(TRUE, forcing)
    rng = np.random.default_rng(seed)
    true_n, true_p = out["cN"][OBS_DAYS], out["cP"][OBS_DAYS]
    sigma_n = NOISE_N[0] + NOISE_N[1] * true_n
    sigma_p = NOISE_P[0] + NOISE_P[1] * true_p
    obs_n = true_n + rng.normal(0, sigma_n)
    obs_p = true_p + rng.normal(0, sigma_p)
    return dict(
        days=OBS_DAYS,
        obsN=np.clip(obs_n, 0.0, None),
        obsP=np.clip(obs_p, 0.0, None),
        trueN=true_n,
        trueP=true_p,
        true_kgN=out["kgN"],
        true_kgP=out["kgP"],
    )


def obs_sigma(obs):
    """Known synthetic error model: sigma = a + b * observed value.

    The same standard deviations are the PEST weights and the fixed-sigma DREAM likelihood.
    """
    return (
        NOISE_N[0] + NOISE_N[1] * obs["obsN"],
        NOISE_P[0] + NOISE_P[1] * obs["obsP"],
    )
